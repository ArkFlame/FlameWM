#[must_use]
pub(crate) fn stable_setting(key: &str) -> Option<&'static StableSetting> {
    let key = if key == "wallpaperShare" {
        "shareWallpaper"
    } else {
        key
    };
    STABLE_SETTINGS.iter().find(|row| row.key == key)
}
